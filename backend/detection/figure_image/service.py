# -*- coding: utf-8 -*-
"""位图图内文字的「未检说明」服务（模板 §5.3「图内字体字号：宋体五号字」）。

为什么这里不判定、也不报任何估计值
----------------------------------
模板对图内的要求是「图内字体字号：宋体五号字」。**位图**（截图/照片/导出的图片）
里的字是像素：图上没有字体名，字号只能从墨迹反推——而这套反推的两条前提都不成立。

1. **字体未知**。五种常见中文字体的「墨迹高 ÷ 字号」实测 0.864（楷体）~ 0.956
   （雅黑），离散约 10%：同一个墨迹高，既能是五号宋体，也能是 4.5 号黑体。
   位图的绝对字号**无法用图片自证**——拿「按估计值渲染出来的字」与原图比大小必然
   一致，两者出自同一个墨迹高，是循环论证。
2. **找不到文字行**。像素分析只能靠行投影找「文字带」；实测 26 份样张，散点图的带
   是整行绘图区（含网格线）、折线图的带是各 y 值横条、流程图的带是方框边框、网页
   截图的带是界面每一行——**没有一张的带是「一行文字」**。投影量到的从来不是字高，
   而是行结构高度；照它报「图内字号约 X pt」就是报错与事实不符。

因此本服务**不产生 issue、不给任何估计值**，只产出一段可核查的未检说明（进
`unchecked`）：陈述「图内文字是位图像素，字体字号无法自动核对」，请人工核对。

矢量图形（形状/文本框，`w:txbxContent` 内的段落）里的文字在 docx 里是真字符，
字体名与字号都明确写着，那边照常精确判定与修复，见 `detection/rules/figure_content.py`。

本模块不依赖任何图像库，也不打开图片文件：只按解析契约的块结构判断「本文有没有位图
插图」，所以它不增加安装/部署负担，也不受图片文件缺失影响。
"""
from __future__ import annotations

__all__ = ["bitmap_figures", "summarize"]

# 只陈述事实与人工核对要求：**不含任何数字**（数量、字号、区间、百分比都不行）。
# 曾经写过「N 张可量出字高，估约 X pt（区间 a–b pt，±2 pt）」与「约 10%」：
# 前者的数字实测量的是行结构高度而不是字高，后者是排版学的一般性数据、
# 不是本文的事实。提示里出现任何数字都会被读成"程序量过了"，所以一个都不留。
_REASON = (
    "本文插图以位图（截图/照片/导出的图片）形式插入，图内文字在图片上只是像素："
    "字体名无处可读，字号也无法从像素可靠反推，程序不做判定。"
    "模板要求「图内字体字号：宋体五号字」，请人工核对。"
)


def bitmap_figures(blocks: list[dict]) -> list[dict]:
    """本文的位图插图块：独立成段的插图。

    与图题规则同一口径（`detection/rules/captions.py`）：段落里除图形还有文字的是
    行内图形（MathType/公式的符号预览图），不是插图；前置区（封面校徽等）图片是版式
    元素，模板的图内条款针对的是论文插图。两者都不算。
    """
    return [block for block in blocks
            if block.get("type") == "image" and not block.get("inline")
            and not block.get("front_matter")]


def summarize(blocks: list[dict]) -> dict:
    """返回 ``{"reason": "…"}``；``reason`` 为空表示本文无需这条说明（没有位图插图）。"""
    if not bitmap_figures(blocks):
        return {"reason": ""}
    return {"reason": _REASON}
